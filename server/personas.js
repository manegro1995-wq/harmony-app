/* Voice + shared methodology — the same composition the client's
   buildSystemPrompt() performs. */
function basePrompt(companion) {
  const voice = THERAPIST_VOICES[companion] || THERAPIST_VOICES.noam;
  return voice + '\n\n' + CONVERSATIONAL_METHODOLOGY;
}

/* Two blocks genuinely must come from the client, because only the client
   knows them: how the companion opened its last few replies, and how the
   user's last message read emotionally.

   They arrive as STRUCTURED data — an array of strings and one enum label
   — and are rebuilt into prompt text here. That distinction is the whole
   security model: a caller can supply a quote or pick a label, but cannot
   supply instructions. An unrecognised label is dropped, never echoed. */
function openersBlock(recentOpeners) {
  const list = (Array.isArray(recentOpeners) ? recentOpeners : [])
    .filter(o => typeof o === 'string' && o.trim())
    .slice(-4)
    .map(o => o.replace(/[\r\n]+/g, ' ').slice(0, 200));
  if (!list.length) return '';
  return '\n\n── פתיחות אחרונות (אל תחזור עליהן) ──\n'
    + 'כך פתחת את התגובות האחרונות שלך מול {{NAME}}. אל תשתמש באף אחת מהן שוב, ולא בניסוח קרוב אליהן. פתח אחרת:\n'
    + list.map(o => '• ' + o).join('\n');
}

function emotionBlock(label) {
  if (!label || label === 'neutral') return '';
  const directive = EMOTION_DIRECTIVES[label];
  const he = EMOTION_LABELS_HE[label];
  if (!directive || !he) return '';
  return '\n\n── קריאת רגש (Emotion Engine) ──\n'
    + 'ההודעה האחרונה של {{NAME}} נקראה כ**' + he + '**.\n'
    + 'זו קריאה אוטומטית של המערכת, לא עובדה. אם מה ש{{NAME}} כתב אומר לך משהו אחר — לך אחרי מה שהוא כתב, לא אחרי השורה הזו. לעולם אל תגיד לו איזה רגש "זוהה" אצלו; זה משנה איך אתה נשמע, לא על מה אתה מדבר.\n'
    + 'הטון שנדרש כאן: ' + directive;
}

/* {{NAME}} is resolved from an already-sanitised value (see server.js).
   A name is a name: no newlines, no braces, length-capped. */

/* Returned as TWO blocks, and the split is the whole point.

   The voice + methodology is ~9,400 characters — roughly 3,000 tokens —
   and it is byte-identical on every single message of a conversation.
   Sent as one flat string, you pay full input price for all 3,000 of
   them on every turn, forever.

   Prompt caching is prefix-matched: anything before the cache marker
   must be identical or the cache misses. So the stable half goes first
   and carries the marker, and everything that changes per turn — the
   do-not-repeat openers, the emotion reading, the app context — goes
   after it, uncached.

   {{NAME}} is resolved inside the stable block, which means the cache is
   per-person rather than global. That is fine and still worth it: a
   conversation is many turns within a few minutes, the TTL refreshes on
   every hit, so turn 1 writes and turns 2..n read at a tenth of the
   price. Pulling the name out to make the cache global would mean
   rewriting all six personas in the second person, which would change
   how they sound — a bad trade for a rounding error. */
export function composeSystemBlocks({ companion, userName, recentOpeners, emotion }) {
  const name = userName || 'חבר';
  const sub = t => t.replace(/\{\{NAME\}\}/g, name);
  return {
    stable: sub(basePrompt(companion)),
    dynamic: sub(openersBlock(recentOpeners) + emotionBlock(emotion))
  };
}

/* Kept for callers that want one string (tests, non-streaming paths). */
export function composeSystemPrompt(v) {
  const b = composeSystemBlocks(v);
  return b.stable + b.dynamic;
}

